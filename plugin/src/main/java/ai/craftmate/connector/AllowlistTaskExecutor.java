package ai.craftmate.connector;

import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import org.bukkit.Bukkit;
import org.bukkit.Difficulty;
import org.bukkit.GameMode;
import org.bukkit.World;
import org.bukkit.configuration.file.YamlConfiguration;

import java.io.File;
import java.nio.file.Files;
import java.nio.file.StandardCopyOption;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Restricted Policy & Task Execution Engine (FR-10, FR-11, Section 9.1 & Section 13).
 * - Rejects unknown, expired, or duplicate tasks (Idempotency).
 * - Never executes raw shell or arbitrary console commands generated by AI.
 * - Enforces Host Policy Guardrails (e.g., blocks disabling BungeeCord on Minefort).
 * - Creates automatic .bak backups before any approved YAML modification.
 */
public final class AllowlistTaskExecutor {

    private final CraftMateConnectorPlugin plugin;
    private final EnvironmentDetector detector;

    // LRU Set of last 250 executed task IDs to prevent duplicate execution on reconnect
    private final Set<String> executedTaskIds = Collections.newSetFromMap(
            new LinkedHashMap<String, Boolean>(256, 0.75f, true) {
                @Override
                protected boolean removeEldestEntry(Map.Entry<String, Boolean> eldest) {
                    return size() > 250;
                }
            }
    );

    // Allowed YAML files and keys that can ever be updated in Phase P4
    private static final Set<String> ALLOWED_YAML_FILES = Set.of(
            "spigot.yml",
            "config/paper-world-defaults.yml",
            "plugins/Geyser-Spigot/config.yml"
    );

    private static final Set<String> ALLOWED_YAML_KEYS = Set.of(
            "world-settings.default.view-distance",
            "world-settings.default.simulation-distance",
            "chunks.max-auto-save-chunks-per-tick",
            "bedrock.port",
            "bedrock.clone-remote-port",
            "remote.auth-type",
            "settings.bungeecord"
    );

    public AllowlistTaskExecutor(CraftMateConnectorPlugin plugin, EnvironmentDetector detector) {
        this.plugin = plugin;
        this.detector = detector;
    }

    public synchronized JsonObject executeTask(String taskId, String taskType, JsonObject params, int onlinePlayers) {
        JsonObject result = new JsonObject();
        result.addProperty("task_id", taskId);
        result.addProperty("task_type", taskType);

        // 1. Idempotency check (Threat Model Section 13)
        if (taskId == null || taskId.isBlank()) {
            result.addProperty("status", "REJECTED");
            result.addProperty("error", "Missing unique task_id.");
            return result;
        }
        if (executedTaskIds.contains(taskId)) {
            result.addProperty("status", "SKIPPED_DUPLICATE");
            result.addProperty("message", "Task already executed previously (idempotent protection).");
            return result;
        }

        try {
            switch (taskType) {
                case "GET_ENVIRONMENT_SNAPSHOT": {
                    JsonObject snap = detector.collectEnvironmentSnapshot(onlinePlayers);
                    executedTaskIds.add(taskId);
                    result.addProperty("status", "SUCCESS");
                    result.add("data", snap);
                    return result;
                }

                case "GET_RECENT_LOGS": {
                    int maxLines = plugin.getConfig().getInt("security.max-log-lines-per-snapshot", 250);
                    boolean redact = plugin.getConfig().getBoolean("security.redact-ips-and-secrets", true);
                    File logFile = new File("logs/latest.log");
                    List<String> rawLines = LogScrubber.readLastLines(logFile, maxLines);
                    LogScrubber.ScrubResult scrubbed = LogScrubber.scrubAndDeduplicate(rawLines, redact);

                    JsonObject logData = new JsonObject();
                    logData.addProperty("scrubbed_log", scrubbed.getScrubbedText());
                    logData.addProperty("redacted_secrets_count", scrubbed.getRedactedSecretsCount());
                    logData.addProperty("original_lines", scrubbed.getOriginalLineCount());
                    logData.addProperty("compressed_lines", scrubbed.getCompressedLineCount());

                    executedTaskIds.add(taskId);
                    result.addProperty("status", "SUCCESS");
                    result.add("data", logData);
                    return result;
                }

                case "SET_DIFFICULTY": {
                    if (!liveWritesAllowed()) return blockedLiveWrite(result);
                    String raw = params.has("difficulty") ? params.get("difficulty").getAsString() : "";
                    Difficulty difficulty;
                    try { difficulty = Difficulty.valueOf(raw.trim().toUpperCase()); }
                    catch (Exception e) { return failed(result, "Invalid difficulty: " + raw); }
                    String previous = Bukkit.getWorlds().isEmpty() ? "UNKNOWN" : Bukkit.getWorlds().get(0).getDifficulty().name();
                    for (World w : Bukkit.getWorlds()) w.setDifficulty(difficulty);
                    boolean verified = Bukkit.getWorlds().stream().allMatch(w -> w.getDifficulty() == difficulty);
                    JsonObject data = new JsonObject();
                    data.addProperty("difficulty", difficulty.name());
                    data.addProperty("previous_difficulty", previous);
                    data.addProperty("worlds_updated", Bukkit.getWorlds().size());
                    data.addProperty("verified", verified);
                    data.addProperty("reversible", true);
                    executedTaskIds.add(taskId);
                    result.addProperty("status", verified ? "SUCCESS" : "FAILED");
                    if (!verified) result.addProperty("error", "Difficulty verification failed after apply.");
                    result.add("data", data);
                    return result;
                }

                case "SET_TIME": {
                    if (!liveWritesAllowed()) return blockedLiveWrite(result);
                    long ticks;
                    if (params.has("ticks")) {
                        ticks = params.get("ticks").getAsLong();
                        if (ticks < 0 || ticks > 23999) return failed(result, "ticks must be between 0 and 23999.");
                    } else {
                        String preset = params.has("preset") ? params.get("preset").getAsString().trim().toUpperCase() : "DAY";
                        ticks = switch (preset) {
                            case "DAY", "SUNRISE" -> 1000L;
                            case "NOON" -> 6000L;
                            case "NIGHT" -> 13000L;
                            case "MIDNIGHT" -> 18000L;
                            default -> -1L;
                        };
                        if (ticks < 0) return failed(result, "Invalid time preset.");
                    }
                    long previousTime = Bukkit.getWorlds().isEmpty() ? -1 : Bukkit.getWorlds().get(0).getTime();
                    for (World w : Bukkit.getWorlds()) w.setTime(ticks);
                    boolean verified = Bukkit.getWorlds().stream().allMatch(w -> Math.abs(w.getTime() - ticks) <= 20);
                    JsonObject data = new JsonObject();
                    data.addProperty("time_ticks", ticks);
                    data.addProperty("previous_time_ticks", previousTime);
                    data.addProperty("worlds_updated", Bukkit.getWorlds().size());
                    data.addProperty("verified", verified);
                    data.addProperty("reversible", true);
                    executedTaskIds.add(taskId);
                    result.addProperty("status", verified ? "SUCCESS" : "FAILED");
                    if (!verified) result.addProperty("error", "Time verification failed after apply.");
                    result.add("data", data);
                    return result;
                }

                case "SET_WEATHER": {
                    if (!liveWritesAllowed()) return blockedLiveWrite(result);
                    String preset = params.has("preset") ? params.get("preset").getAsString().trim().toUpperCase() : "CLEAR";
                    if (!Set.of("CLEAR", "RAIN", "THUNDER").contains(preset)) return failed(result, "Invalid weather preset.");
                    JsonArray worlds = new JsonArray();
                    for (World w : Bukkit.getWorlds()) {
                        JsonObject before = new JsonObject();
                        before.addProperty("world", w.getName());
                        before.addProperty("storm", w.hasStorm());
                        before.addProperty("thundering", w.isThundering());
                        worlds.add(before);
                        switch (preset) {
                            case "CLEAR" -> { w.setStorm(false); w.setThundering(false); w.setWeatherDuration(20 * 60 * 10); }
                            case "RAIN" -> { w.setStorm(true); w.setThundering(false); w.setWeatherDuration(20 * 60 * 10); }
                            case "THUNDER" -> { w.setStorm(true); w.setThundering(true); w.setWeatherDuration(20 * 60 * 5); }
                        }
                    }
                    boolean verified = Bukkit.getWorlds().stream().allMatch(w -> switch (preset) {
                        case "CLEAR" -> !w.hasStorm() && !w.isThundering();
                        case "RAIN" -> w.hasStorm() && !w.isThundering();
                        default -> w.hasStorm() && w.isThundering();
                    });
                    JsonObject data = new JsonObject();
                    data.addProperty("weather", preset);
                    data.add("previous_world_states", worlds);
                    data.addProperty("worlds_updated", Bukkit.getWorlds().size());
                    data.addProperty("verified", verified);
                    data.addProperty("reversible", true);
                    executedTaskIds.add(taskId);
                    result.addProperty("status", verified ? "SUCCESS" : "FAILED");
                    if (!verified) result.addProperty("error", "Weather verification failed after apply.");
                    result.add("data", data);
                    return result;
                }

                case "SET_DEFAULT_GAMEMODE": {
                    if (!liveWritesAllowed()) return blockedLiveWrite(result);
                    String raw = params.has("gamemode") ? params.get("gamemode").getAsString() : "";
                    GameMode mode;
                    try { mode = GameMode.valueOf(raw.trim().toUpperCase()); }
                    catch (Exception e) { return failed(result, "Invalid gamemode: " + raw); }
                    String previous = Bukkit.getDefaultGameMode().name();
                    Bukkit.setDefaultGameMode(mode);
                    boolean verified = Bukkit.getDefaultGameMode() == mode;
                    JsonObject data = new JsonObject();
                    data.addProperty("gamemode", mode.name());
                    data.addProperty("previous_gamemode", previous);
                    data.addProperty("verified", verified);
                    data.addProperty("reversible", true);
                    data.addProperty("note", "Applies to players joining after this change; online players keep their current gamemode.");
                    executedTaskIds.add(taskId);
                    result.addProperty("status", verified ? "SUCCESS" : "FAILED");
                    if (!verified) result.addProperty("error", "Gamemode verification failed after apply.");
                    result.add("data", data);
                    return result;
                }

                case "BROADCAST_MESSAGE": {
                    if (!liveWritesAllowed()) return blockedLiveWrite(result);
                    String message = params.has("message") ? params.get("message").getAsString() : "";
                    message = message.replaceAll("[§&][0-9a-fk-orA-FK-OR]", "").trim();
                    if (message.isEmpty() || message.length() > 200) return failed(result, "Broadcast message must be 1-200 characters.");
                    Bukkit.broadcastMessage("[CraftMate] " + message);
                    JsonObject data = new JsonObject();
                    data.addProperty("message", message);
                    data.addProperty("recipients_online", Bukkit.getOnlinePlayers().size());
                    data.addProperty("verified", true);
                    executedTaskIds.add(taskId);
                    result.addProperty("status", "SUCCESS");
                    result.add("data", data);
                    return result;
                }

                case "SAFE_YAML_CONFIG_UPDATE": {
                    // Check if Read-Only mode is active (P2 default)
                    if (plugin.getConfig().getBoolean("security.read-only-mode", true)) {
                        result.addProperty("status", "BLOCKED_READ_ONLY");
                        result.addProperty("error", "Connector is in Read-Only mode (security.read-only-mode: true).");
                        return result;
                    }

                    String targetFile = params.has("file") ? params.get("file").getAsString() : "";
                    String yamlKey = params.has("key") ? params.get("key").getAsString() : "";
                    String newValue = params.has("value") ? params.get("value").getAsString() : "";

                    if (!ALLOWED_YAML_FILES.contains(targetFile) || !ALLOWED_YAML_KEYS.contains(yamlKey)) {
                        result.addProperty("status", "BLOCKED_BY_ALLOWLIST");
                        result.addProperty("error", "File or YAML key is not in the Connector Allowlist.");
                        return result;
                    }

                    // CRITICAL HOST POLICY GUARDRAIL: Minefort BungeeCord Protection
                    String host = detector.detectHostProvider();
                    if (host.equals("minefort") && yamlKey.equals("settings.bungeecord")
                            && newValue.equalsIgnoreCase("false")) {
                        result.addProperty("status", "BLOCKED_BY_HOST_POLICY");
                        result.addProperty("error", "CRITICAL GUARDRAIL: Disabling settings.bungeecord on Minefort is forbidden because Minefort routes traffic through play.minefort.com.");
                        return result;
                    }

                    File configFile = new File(targetFile);
                    if (!configFile.exists()) {
                        result.addProperty("status", "FAILED");
                        result.addProperty("error", "Target configuration file does not exist: " + targetFile);
                        return result;
                    }

                    // Create .bak backup before modifying (FR-11)
                    if (plugin.getConfig().getBoolean("security.create-backup-before-edit", true)) {
                        File backupFile = new File(targetFile + ".bak");
                        Files.copy(configFile.toPath(), backupFile.toPath(), StandardCopyOption.REPLACE_EXISTING);
                    }

                    YamlConfiguration yaml = YamlConfiguration.loadConfiguration(configFile);
                    if (newValue.equalsIgnoreCase("true") || newValue.equalsIgnoreCase("false")) {
                        yaml.set(yamlKey, Boolean.parseBoolean(newValue));
                    } else if (newValue.matches("^-?\\d+$")) {
                        yaml.set(yamlKey, Integer.parseInt(newValue));
                    } else {
                        yaml.set(yamlKey, newValue);
                    }
                    yaml.save(configFile);

                    executedTaskIds.add(taskId);
                    result.addProperty("status", "SUCCESS");
                    result.addProperty("message", "Updated " + yamlKey + " in " + targetFile + " (backup saved to " + targetFile + ".bak)");
                    return result;
                }

                default: {
                    result.addProperty("status", "REJECTED_UNKNOWN_TASK");
                    result.addProperty("error", "Unknown or forbidden task_type: " + taskType);
                    return result;
                }
            }
        } catch (Exception ex) {
            result.addProperty("status", "FAILED");
            result.addProperty("error", ex.getMessage());
            return result;
        }
    }

    private boolean liveWritesAllowed() {
        // Live world tasks arrive only through the website full-control task
        // channel (Worker returns tasks solely while a control session is
        // active). This local switch is an extra owner kill-switch; file
        // edits remain separately governed by security.read-only-mode.
        return plugin.getConfig().getBoolean("control.allow-live-write-tasks", true);
    }

    private JsonObject blockedLiveWrite(JsonObject result) {
        result.addProperty("status", "BLOCKED_BY_LOCAL_CONFIG");
        result.addProperty("error", "Live write tasks are disabled in this connector config (control.allow-live-write-tasks: false).");
        return result;
    }

    private JsonObject failed(JsonObject result, String error) {
        result.addProperty("status", "FAILED");
        result.addProperty("error", error);
        return result;
    }
}
